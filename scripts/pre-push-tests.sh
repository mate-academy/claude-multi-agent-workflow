#!/usr/bin/env bash

# Перевіряємо, чи в команді інструменту Bash є "git push"
if echo "$CLAUDE_TOOL_INPUT" | grep -q "git push"; then
  echo "----------------------------------------------------"
  echo "🔍 [Pre-Push Hook] Виявлено спробу git push."
  echo "🧪 Запускаємо npm test для перевірки коду..."
  echo "----------------------------------------------------"

  # Запускаємо npm test
  if ! npm test; then
    echo "----------------------------------------------------"
    echo "❌ [Pre-Push Hook] ПУШ СКАСОВАНО!"
    echo "⚠️  Один або декілька тестів упали (див. лог вище)."
    echo "Виправте помилки перед повторною спробою пушу."
    echo "----------------------------------------------------"
    exit 1
  fi

  echo "----------------------------------------------------"
  echo "✅ Усі тести успішно пройшли. Продовжуємо push..."
  echo "----------------------------------------------------"
fi

exit 0